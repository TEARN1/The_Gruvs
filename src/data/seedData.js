export const generateMockEvents = (count = 100) => {
  const events = [];
  const catKeys = Object.keys(PRIMARY_CATEGORIES);

  for (let i = 0; i < count; i++) {
    const parent = catKeys[Math.floor(Math.random() * catKeys.length)];
    const sub = PRIMARY_CATEGORIES[parent][Math.floor(Math.random() * PRIMARY_CATEGORIES[parent].length)];
    const adj = ADJECTIVES[Math.floor(Math.random() * ADJECTIVES.length)];
    const place = PLACES[Math.floor(Math.random() * PLACES.length)];

    events.push({
      id: `gen-${i}`,
      title: `${adj} ${sub} @ ${place}`,
      category: sub,
      parentCategory: parent,
      description: `Join us for an amazing ${sub} experience. This is a ${adj.toLowerCase()} gathering for like-minded people.`,
      location: `${place} Location`,
      score: Math.floor(Math.random() * 40) + 60,
      image: `https://picsum.photos/seed/${i}/400/300`,
      time: 'Tomorrow at 6 PM',
      author: {
        id: `u-${i}`,
        name: i === 0 ? 'Mr. Gatsby' : `User ${i}`,
        avatar: `https://i.pravatar.cc/150?u=${i}`,
        profileType: (i === 0 || Math.random() > 0.8) ? 'business' : 'normal'
      }
    });
  }
  return events;
};
